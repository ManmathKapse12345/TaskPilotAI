"use client";

import { useState } from "react";
import type { TaskResult } from "@/lib/api";
import type { LogLine } from "@/lib/taskState";
import { JsonViewer } from "./JsonViewer";
import { LogConsole } from "./LogConsole";
import { Markdown, cx, formatMs } from "./ui";

type Tab = "summary" | "data" | "json" | "logs";

export function ResultTabs({ result, logs, taskId }: { result: TaskResult; logs: LogLine[]; taskId: string }) {
  const hasJson = !!result.json_output;
  const [tab, setTab] = useState<Tab>(result.summary ? "summary" : hasJson ? "json" : "logs");
  const tabs: { key: Tab; label: string; show: boolean }[] = [
    { key: "summary", label: "Summary", show: !!result.summary },
    { key: "data", label: "Extracted Data", show: !!result.data },
    { key: "json", label: "JSON Output", show: hasJson },
    { key: "logs", label: `Execution Logs (${logs.length})`, show: true },
  ];

  return (
    <div className="rounded-lg border border-slate-800 bg-slate-900/40">
      <div className="flex gap-1 overflow-x-auto border-b border-slate-800 px-2 pt-2">
        {tabs.filter((t) => t.show).map((t) => (
          <button key={t.key} onClick={() => setTab(t.key)}
            className={cx("whitespace-nowrap rounded-t-md px-3 py-1.5 text-xs font-medium transition",
              tab === t.key ? "bg-slate-800 text-white" : "text-slate-400 hover:text-slate-200")}>
            {t.label}
          </button>
        ))}
      </div>
      <div className="p-4">
        {tab === "summary" && result.summary && <SummaryView result={result} />}
        {tab === "data" && result.data && <DataView result={result} />}
        {tab === "json" && result.json_output && <JsonViewer value={result.json_output} filename={`taskpilot-${taskId}.json`} />}
        {tab === "logs" && <LogConsole logs={logs} tall />}
      </div>
    </div>
  );
}

function SummaryView({ result }: { result: TaskResult }) {
  const s = result.summary!;
  return (
    <div className="space-y-4 text-sm text-slate-300">
      <div className="flex flex-wrap items-center gap-2 text-[11px] text-slate-500">
        <span className="rounded bg-slate-800 px-1.5 py-0.5">generated by {s.generated_by}</span>
        {s.site_type && <span className="rounded bg-slate-800 px-1.5 py-0.5">type: {s.site_type}</span>}
        <span>· based only on content captured by the CLI</span>
      </div>
      <Markdown text={s.text} />
      {s.key_points.length > 0 && (
        <div>
          <h4 className="mb-1.5 text-xs font-semibold uppercase tracking-wide text-slate-500">Key points</h4>
          <ul className="list-disc space-y-1 pl-5">{s.key_points.map((k, i) => <li key={i}>{k}</li>)}</ul>
        </div>
      )}
      {Object.keys(s.focus_findings || {}).length > 0 && (
        <div>
          <h4 className="mb-1.5 text-xs font-semibold uppercase tracking-wide text-slate-500">What you asked about</h4>
          <dl className="space-y-1.5">
            {Object.entries(s.focus_findings).map(([k, v]) => (
              <div key={k} className="rounded-md bg-slate-800/50 px-3 py-2">
                <dt className="text-xs font-medium capitalize text-indigo-300">{k}</dt>
                <dd className="text-slate-300">{v}</dd>
              </div>
            ))}
          </dl>
        </div>
      )}
    </div>
  );
}

function Field({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="rounded-md bg-slate-800/40 px-3 py-2">
      <div className="text-[11px] font-medium uppercase tracking-wide text-slate-500">{label}</div>
      <div className="mt-0.5 break-words text-sm text-slate-200">{children || <span className="text-slate-600">not found</span>}</div>
    </div>
  );
}

function DataView({ result }: { result: TaskResult }) {
  const d = result.data!;
  const st = d.crawl_stats;
  return (
    <div className="space-y-5 text-sm">
      <div className="grid grid-cols-2 gap-2 sm:grid-cols-4">
        {[["Pages crawled", st.pages_crawled], ["Pages failed", st.pages_failed], ["Robots-skipped", st.pages_skipped_robots],
          ["Downloaded", `${(st.bytes_downloaded / 1024).toFixed(1)} KB`]].map(([k, v]) => (
          <div key={k as string} className="rounded-md border border-slate-800 px-3 py-2">
            <div className="text-lg font-semibold text-white">{v}</div>
            <div className="text-[11px] text-slate-500">{k}</div>
          </div>
        ))}
      </div>

      <div className="grid gap-2 sm:grid-cols-2">
        <Field label="Title">{d.website.title}</Field>
        <Field label="Final URL">{d.website.final_url}</Field>
        <div className="sm:col-span-2"><Field label="Description">{d.website.description}</Field></div>
        <Field label="Language">{d.website.language}</Field>
        <Field label="Emails">{d.contact.emails.join(", ")}</Field>
        <Field label="Phones">{d.contact.phones.join(", ")}</Field>
        <Field label="Social profiles">{d.contact.social_profiles.map((s) => s.platform).join(", ")}</Field>
      </div>

      <div>
        <h4 className="mb-2 text-xs font-semibold uppercase tracking-wide text-slate-500">Pages ({d.pages.length})</h4>
        <div className="space-y-2">
          {d.pages.map((p) => (
            <details key={p.url} className="group rounded-md border border-slate-800 bg-slate-900/60 px-3 py-2">
              <summary className="flex cursor-pointer list-none items-center justify-between gap-2">
                <span className="min-w-0">
                  <span className="block truncate font-medium text-slate-200">{p.title || p.url}</span>
                  <span className="block truncate font-mono text-[11px] text-slate-500">{p.url}</span>
                </span>
                <span className="shrink-0 text-[11px] text-slate-500">HTTP {p.status_code} · {p.word_count} words · depth {p.depth}</span>
              </summary>
              <div className="mt-2 space-y-2 border-t border-slate-800 pt-2 text-xs text-slate-400">
                {p.description && <p>{p.description}</p>}
                {p.headings.length > 0 && (
                  <ul className="space-y-0.5">
                    {p.headings.slice(0, 12).map((h, i) => (
                      <li key={i} style={{ paddingLeft: (h.level - 1) * 12 }}><span className="text-slate-600">H{h.level}</span> {h.text}</li>
                    ))}
                  </ul>
                )}
                {p.content_preview && <p className="italic text-slate-500">“{p.content_preview.slice(0, 300)}…”</p>}
              </div>
            </details>
          ))}
        </div>
      </div>

      {d.navigation_links.length > 0 && (
        <div>
          <h4 className="mb-2 text-xs font-semibold uppercase tracking-wide text-slate-500">Key internal links</h4>
          <div className="flex flex-wrap gap-1.5">
            {d.navigation_links.slice(0, 20).map((l) => (
              <a key={l.url} href={l.url} target="_blank" rel="noopener noreferrer nofollow"
                className="rounded-full bg-slate-800 px-2.5 py-0.5 text-xs text-slate-300 hover:bg-slate-700">{l.text}</a>
            ))}
          </div>
        </div>
      )}

      {st.errors.length > 0 && (
        <div className="rounded-md border border-amber-500/30 bg-amber-500/10 p-3 text-xs text-amber-200">
          <div className="mb-1 font-semibold">Pages that failed</div>
          <ul className="space-y-0.5 font-mono">{st.errors.map((e, i) => <li key={i}>{e.url} — {e.error}</li>)}</ul>
        </div>
      )}
      <p className="text-[11px] text-slate-600">Crawl took {formatMs(st.duration_ms)} inside the CLI process.</p>
    </div>
  );
}
